void * __astex_fopen(const char * name, const char * mode)
{
  FILE* f;
  f=fopen(name, mode);
  if (f==NULL)
  {
    printf("Error: can't open file %s\n", name);
    exit(1);
  }

  return f;
}

void * __astex_memalloc(long bytes)
{
 void* b;

 b=malloc(bytes);

 if (b==NULL)
 {
   printf("Error: can't allocate memory\n");
   exit(1);
 }

 return b;
}

