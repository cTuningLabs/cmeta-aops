{
 fread(dest, 1, bytes, file);
}

int __astex_getenv_int(const char * var)
{
 char* p;
 int r=1;

 p=getenv(var);
 if (p!=NULL) r=atoi(p);

 return r;
}

void * __astex_start_measure()
{
 printf("Start codelet\n");
 start_clock();
}

double __astex_stop_measure(void * _before)
{
  FILE* f;

  stop_clock();

  printf("Stop codelet\n");

  f=fopen(ck_time_file, "w");
  if (f==NULL)
  {
    printf("Error: can't open timer file %s for writing\n", ck_time_file);
    exit(1);
  }

  fprintf(f,"{\n");
  fprintf(f,"  \"execution_time\":%.6lf,\n", secs);
  fprintf(f,"  \"execution_time_kernel_0\":%.6lf\n", secs);
  fprintf(f,"}\n");


  fclose(f);

  return timer_length;
}
