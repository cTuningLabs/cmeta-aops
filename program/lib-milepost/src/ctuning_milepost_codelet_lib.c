#ifdef __MINGW32__
# include <sys/time.h>
#else
# ifdef WINDOWS
#  include <time.h>
# else
#  include <sys/time.h>
# endif
#endif

#include <stdio.h>
#include <stdlib.h>

double timer_start, timer_length;
char* ck_time_file="tmp-ck-timer.json";

#ifdef WINDOWS
static clock_t start=0.0, stop=0.0;
#else 
static double start=0.0, stop=0.0;
static struct timeval  before, after, acc_before, acc_after;
#endif
static double secs;

static void start_clock()
{

#ifdef WINDOWS
  start = clock();
#else
  gettimeofday(&before, NULL);
#endif
}

static void stop_clock()
{
#ifdef WINDOWS
  stop = clock();
  secs = ((double)(stop - start)) / CLOCKS_PER_SEC;
#else
  gettimeofday(&after, NULL);
  secs = (after.tv_sec - before.tv_sec) + (after.tv_usec - before.tv_usec)/1000000.0;
#endif
}

