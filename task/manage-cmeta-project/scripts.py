def shared_files():
    """The adapters of a home: current instance: they run in the invoking cMeta home and set no CMETA_HOME.
    A background start (--detach) keeps its process id and log in the instance's state artifact."""
    files = {}
    commands = {
        '__info': (MANAGER, 'info', ''),
        '__run_server': (RUNNER, '', '--mode=native'),
        '__run_server_in_docker': (RUNNER, '', '--mode=docker'),
    }
    for name, (task, action, flags) in commands.items():
        files[name + '.bat'] = '''@echo off
setlocal DisableDelayedExpansion

rem Generated by cMeta manage-cmeta-project. Additional arguments override defaults.
rem This website runs in the invoking cMeta home (home: current in project.yaml): no CMETA_HOME is set here.
for %%I in ("%~dp0.") do set "PROJECT_ROOT=%%~fI"

(
cx task run TASK ACTION ^
    --project-home="%PROJECT_ROOT%" ^
    FLAGS ^
    %*

call exit /b %%errorlevel%%
)
'''.replace('TASK', task).replace('ACTION', action).replace('    FLAGS ^\n', ('    ' + flags + ' ^\n') if flags else '')
        files[name + '.sh'] = '''#!/bin/sh
# Generated by cMeta manage-cmeta-project. Additional arguments override defaults.
# This website runs in the invoking cMeta home (home: current in project.yaml): no CMETA_HOME is set here.
set -eu

project_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)

exec cx task run TASK ACTION \\
    --project-home="$project_dir" \\
    FLAGS \\
    "$@"
'''.replace('TASK', task).replace('ACTION', action).replace('    FLAGS \\\n', ('    ' + flags + ' \\\n') if flags else '')
    files['__run_server_nohup.sh'] = '''#!/bin/sh
# Generated by cMeta manage-cmeta-project. Background start in the invoking cMeta home; no service is installed.
# The process id and the output are in the runtime folder of the instance's state artifact:
#   ./__run_server.sh --status | --logs | --stop
set -eu

project_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)

exec cx task run RUNNER \\
    --project-home="$project_dir" \\
    --mode=native \\
    --detach \\
    "$@"
'''.replace('RUNNER', RUNNER)
    return files


def _step(entry):
    """('host', alias) for a host::<alias> entry of syncs:, else ('sync', <alias,UID>)."""
    text = str(entry).strip()
    kind, sep, rest = text.partition('::')
    if sep and kind.split(',')[0] == 'host':
        return 'host', rest
    if sep and kind.split(',')[0] == 'sync':
        return 'sync', rest
    return 'sync', text


def sync_files(profile):
    """___sync_all.bat/.sh from the syncs: list of project.yaml - the ordered steps, each stopping the chain on
    failure; host::<alias> entries run cx host sync, the others cxt sync --require-initialized --live."""
    steps = [_step(s) for s in (profile or {}).get('syncs') or [] if str(s).strip()]
    if not steps:
        return {}
    total = len(steps)
    bat = ['@echo off', 'setlocal DisableDelayedExpansion', '',
           'rem Generated by cMeta manage-cmeta-project from the syncs: list of project.yaml.',
           'rem Run from your usual GLOBAL cMeta orchestrator shell; this script sets no CMETA_HOME.',
           'rem Every step stops the chain on failure; a missing saved state stops it too (--require-initialized).',
           'rem Pass -q to skip prompts, --dry-run to preview, --plan to show the sync artifacts without connecting.']
    sh = ['#!/bin/sh',
          '# Generated by cMeta manage-cmeta-project from the syncs: list of project.yaml.',
          '# Run from your usual GLOBAL cMeta orchestrator shell; this script sets no CMETA_HOME.',
          '# Every step stops the chain on failure; a missing saved state stops it too (--require-initialized).',
          '# Pass -q to skip prompts, --dry-run to preview, --plan to show the sync artifacts without connecting.',
          'set -eu']
    if any(kind == 'host' for kind, _ in steps):
        bat += ['', 'rem cx host sync takes -q and --dry-run; it has no plan, so --plan skips its steps',
                'set "HOST_Q="', 'set "HOST_DRY="', 'set "PLAN="', 'for %%A in (%*) do (',
                '    if /i "%%~A"=="-q" set "HOST_Q=-q"', '    if /i "%%~A"=="--dry-run" set "HOST_DRY=--dry-run"',
                '    if /i "%%~A"=="--plan" set "PLAN=1"', ')']
        sh += ['', '# cx host sync takes -q and --dry-run; it has no plan, so --plan skips its steps',
               "host_flags=''", "plan=''", 'for a in "$@"; do', '    case "$a" in',
               '        -q|--dry-run) host_flags="$host_flags $a" ;;', '        --plan) plan=1 ;;', '    esac', 'done']
    for number, (kind, ref) in enumerate(steps, 1):
        label = '[%d/%d] %s' % (number, total, ('cx host sync ' + ref) if kind == 'host' else ref.split(',')[0])
        bat += ['', 'echo ' + label]
        sh += ['', "echo '" + label + "'"]
        if kind == 'host':
            bat += ['if not defined PLAN (', '    call cx host sync ' + ref + ' %HOST_Q% %HOST_DRY%',
                    '    if errorlevel 1 exit /b 1', ')']
            sh += ['if [ -z "$plan" ]; then', '    cx host sync ' + ref + ' $host_flags', 'fi']
        else:
            command = 'call cxt sync ' + ref + ' --require-initialized --live %*'
            bat += [command] if len(command) < 100 else ['call cxt sync ' + ref + ' ^', '    --require-initialized --live %*']
            bat += ['if errorlevel 1 exit /b %errorlevel%']
            command = 'cxt sync ' + ref + ' --require-initialized --live "$@"'
            sh += [command] if len(command) < 100 else ['cxt sync ' + ref + ' \\', '    --require-initialized --live "$@"']
    name = str((profile or {}).get('name') or 'project')
    bat += ['', 'echo ' + name + ' synchronized.', 'exit /b 0', '']
    sh += ['', "echo '" + name + " synchronized.'", '']
    return {'___sync_all.bat': '\n'.join(bat), '___sync_all.sh': '\n'.join(sh)}


def write_files(root, files):
    """Write the adapters. A generated file that was changed by hand is preserved: archive it first."""
    record = root / '.setup/runtime/generated-scripts.json'
    previous = json.loads(record.read_text(encoding='utf-8')) if record.exists() else {}
    hashes = {}
    for name, text in files.items():
        data = text.replace('\n', '\r\n').encode() if name.endswith('.bat') else text.encode()
        path = root / name
        if path.exists():
            old = path.read_bytes()
            if old != data and hashlib.sha256(old).hexdigest() != previous.get(name):
                raise ValueError('Preserve/archive this existing script before generation: ' + str(path))
        hashes[name] = hashlib.sha256(data).hexdigest()
    for name, text in files.items():
        path = root / name
        data = text.replace('\n', '\r\n').encode() if name.endswith('.bat') else text.encode()
        if not path.exists() or path.read_bytes() != data:
            path.write_bytes(data)
        if name.endswith('.sh'):
            path.chmod(path.stat().st_mode | 0o111)
    record.parent.mkdir(parents=True, exist_ok=True)
    record.write_text(json.dumps(hashes, indent=2) + '\n', encoding='utf-8')
    print('Generated project scripts in ' + str(root), flush=True)


def generate(root, profile=None):
    """Generate the shell adapters of a project home or of a home: current instance, plus ___sync_all when
    project.yaml declares syncs:. Preserve modified generated files unless explicitly archived first."""
    shared = str((profile or {}).get('home') or 'project') == 'current'
    files = shared_files() if shared else project_files()
    files.update(sync_files(profile))
    write_files(root, files)
