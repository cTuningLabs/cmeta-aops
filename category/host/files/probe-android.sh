# Read-only probe of an Android device over adb ("adb shell sh -s", stdin = this file): the same
# "key=value" lines as probe.sh, from getprop. Parsed by host/api/v1.py::probe.
echo "hostname=$(getprop ro.product.model)"
echo "os=Android $(getprop ro.build.version.release) (SDK $(getprop ro.build.version.sdk), $(getprop ro.product.manufacturer) $(getprop ro.product.model))"
echo "kernel=$(uname -sr)"
echo "arch=$(getprop ro.product.cpu.abi)"
echo "serial=$(getprop ro.serialno)"
echo "device=$(getprop ro.product.device)"
echo "build=$(getprop ro.build.display.id)"
echo "security_patch=$(getprop ro.build.version.security_patch)"
echo "uptime=$(uptime 2>/dev/null)"
echo "user=$(id -un 2>/dev/null)"
echo "sudo=none"
echo "docker=-"
echo "podman=-"
echo "cpus=$(nproc 2>/dev/null)"
echo "disk=$(df -h /data 2>/dev/null | tail -1 | awk '{print $4 " free of " $2 " (" $5 " used) on /data"}')"
echo "battery=$(dumpsys battery 2>/dev/null | grep -m1 level | sed 's/.*: *//')%"
